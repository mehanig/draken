import { test, expect } from '@playwright/test';

test('scan → briefing → discussion → finish → remembered second sync, including mobile layout', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Pick up where you left off.' })).toBeVisible();
  await page.getByRole('button', { name: 'Scan local sessions', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Scanned 2 files');
  await page.getByRole('button', { name: 'Start sync', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Sync #1 open' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Generate briefing' })).toBeDisabled();
  await page.getByLabel('Allow briefing and discussion').check();
  await page.getByRole('button', { name: 'Generate briefing' }).click();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Cancel generation', exact: true })).toBeVisible();
  await expect(page.getByText('Needs your attention', { exact: false })).toBeVisible();
  await expect(page.getByText('70 / 70 entries processed', { exact: true })).toBeVisible();
  const citation = page.getByRole('button', { name: /Inspect evidence E/ }).first();
  const reference = (await citation.getAttribute('aria-label'))!.split(' ').pop();
  await citation.click();
  await expect(page.locator(`#evidence-${reference}`)).toHaveAttribute('open', '');
  await page.locator('.tree-browser > summary').click();
  await page.locator('.tree-label').first().click();
  await expect(page.locator('.node-observation').first()).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: '.test-artifacts/mobile-tree.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByLabel('Allow briefing and discussion').check();
  await page.getByRole('textbox', { name: 'Ask Draken about this sync' }).fill('Did we validate it?');
  await page.getByRole('button', { name: 'Ask Draken', exact: true }).click();
  await expect(page.getByText('The session reports targeted tests passing, not a deployment.', { exact: false })).toBeVisible();
  await expect(page.getByText('1 / 120 pi invocations', { exact: true })).toBeVisible();
  await page.getByLabel('Decisions', { exact: true }).fill('Validate exports before changing dashboard behavior.');
  await page.getByLabel('Carry into the next sync', { exact: true }).fill('Choose polling versus events.');
  await page.getByRole('button', { name: 'Save notes', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Notes saved');
  await page.screenshot({ path: '.test-artifacts/desktop-sync.png', fullPage: true });
  await page.reload();
  await expect(page.getByLabel('Decisions', { exact: true })).toHaveValue('Validate exports before changing dashboard behavior.');
  await expect(page.getByRole('button', { name: 'Finish sync', exact: true })).toBeDisabled();
  await page.getByLabel('I reviewed this snapshot.').check();
  await page.getByRole('button', { name: 'Finish sync', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Sync #1 completed' })).toBeVisible();
  await expect(page.locator('.stats')).toContainText('0 uncovered entries');
  await page.getByRole('button', { name: 'Start sync', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Sync #2 open' })).toBeVisible();
  await expect(page.getByLabel('Carry into the next sync', { exact: true })).toHaveValue('Choose polling versus events.');
  await page.getByText('Memory from previous syncs', { exact: true }).click();
  await expect(page.getByText('Validate exports before changing dashboard behavior.', { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('heading', { name: 'Pick up where you left off.' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: '.test-artifacts/mobile-sync.png', fullPage: true });
  expect(errors).toEqual([]);
});
